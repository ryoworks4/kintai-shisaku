/**
 * 勤怠システム（試作）— 職員の画面（出勤・退勤）
 *
 * 押した瞬間に表示を変え、裏の確定はあとから届く。
 * 届かない間は「待ち」として端末にしまい、同じ操作IDで送り直す（裏で1回分にまとまる）。
 * 待ちは押した時のトークンに結び付ける。登録が変わったら送らない（ほかの人の打刻にしない）。
 * 「届いたか分からない」待ちは捨てさせない。捨ててから押し直すと、届いていた時に二重になるため。
 * 時刻は裏が決める（届いた時点）ので、時間がたってから開き直した時は、送り直す前に操作IDで照会する。
 */
(function () {
  if (埋め込まれていたら止める()) return;

  // 送る前の待ち（ミリ秒）。1回は最大8秒で切れる（common.js）。電波がない時は約40秒で帯が出る
  var 送り直しの間隔 = [0, 0, 2000, 5000, 10000, 20000];
  var 自動で送り直す時間 = 2 * 60000;   // 開き直した時、押してからこれ以内なら照会せずに送り直す
  var 読み直しの間隔 = 5000;            // ほかのアプリから戻るたびに読みすぎない

  var 鍵 = 取り出す('トークン');
  var 待ち = 取り出す('待ち');          // { 操作ID, 種類, 押した(ミリ秒), 鍵(押した時のトークン) }
  var 待ちの様子 = '';                  // '' 確認できない / '照会中' / '届いていない' / '取り消し中' / '別の登録'
  var 記録 = [];                        // 自分の直近の記録（新しい順）
  var 送っている = false;
  var 状態の文 = '';
  var 読んでいる = false;
  var 最後に読んだ = 0;
  var 届いた回数 = 0;

  要素('今日').textContent = 今日の表示();
  要素('出勤').addEventListener('click', function () { 押した('出勤'); });
  要素('退勤').addEventListener('click', function () { 押した('退勤'); });
  // 戻ってきた時に読み直す。同じ人がほかの端末で押した分や、日付の変わり目を反映するため
  document.addEventListener('visibilitychange', function () {
    if (document.visibilityState !== 'visible' || !鍵) return;
    要素('今日').textContent = 今日の表示();
    描く();
    if (!送っている && Date.now() - 最後に読んだ > 読み直しの間隔) 読み込む(false);
  });

  if (鍵) 読み込む(true); else 登録の画面を出す('', 登録できた);

  function 登録できた(応答) {
    鍵 = 応答.トークン;
    読み込む(true);
  }

  /** 初めて = true の時だけ「読み込んでいます」を出す。戻ってきた時は今の表示のまま裏で読み直す */
  function 読み込む(初めて) {
    if (読んでいる) return;
    読んでいる = true;
    var 読む前の届いた回数 = 届いた回数;
    if (初めて) 画面を切り替える('読み込み中');
    送り直しつきで送る({ 操作: '自分の記録', トークン: 鍵 }, function (r) {
      return typeof r.名前 === 'string' && typeof r.役割 === 'string' &&
          Array.isArray(r.記録) && r.記録.every(打刻の形か);
    }).then(function (結果) {
      読んでいる = false;
      if (!結果.届いた) {
        // 戻ってきた時の読み直しが失敗しても、今の表示のまま使える（押せば送れる）
        if (初めて) {
          知らせる('読み込めませんでした。電波のよい所で、もう一度ためしてください。', {
            名前: 'もう一度', 押したら: function () { 読み込む(true); }
          });
        }
        return;
      }
      if (!結果.応答.ok) { 断られた(結果.応答); return; }
      最後に読んだ = Date.now();
      要素('名前').textContent = 結果.応答.名前 + ' さん';
      要素('代表へ').hidden = 結果.応答.役割 !== '管理者';
      // 読んでいる間に打刻が届いていたら、この一覧にはその分が無いので使わない
      if (届いた回数 === 読む前の届いた回数) 記録 = 結果.応答.記録;
      画面を切り替える('本体');
      描く();
      if (初めて && 待ち) 待ちを片づける();
    });
  }

  /** 開き直した時に残っていた待ちを、送り直すか・照会するか・止めるかに分ける */
  function 待ちを片づける() {
    if (待ち.鍵 !== 鍵) { 待ちの様子 = '別の登録'; 描く(); return; }
    if (Date.now() - 待ち.押した < 自動で送り直す時間) { 送り続ける(); return; }
    待ちの様子 = '照会中';
    描く();
    var 照会する待ち = 待ち;
    送り直しつきで送る({ 操作: '打刻を探す', トークン: 鍵, 操作ID: 照会する待ち.操作ID }, function (r) {
      return r.操作ID === 照会する待ち.操作ID && (r.記録 === null || (打刻の形か(r.記録) && r.記録.種類 === 照会する待ち.種類));
    }).then(function (結果) {
      if (待ち !== 照会する待ち) return;
      if (!結果.届いた) { 待ちの様子 = ''; 描く(); return; }
      if (!結果.応答.ok) { 待ちの様子 = ''; 断られた(結果.応答); return; }
      if (結果.応答.記録) { 届いた(結果.応答.記録); return; }
      if (結果.応答.取り消し済み) { 待ちを消す(); 状態の文 = '記録しないことにしてあります'; 描く(); return; }
      待ちの様子 = '届いていない';
      描く();
    });
  }

  /**
   * 「記録しない」。裏に取消を伝えてから待ちを消す。元の依頼があとから届いても、裏は記録しない。
   * 取り消す前にもう届いていた時は、裏がその記録を返すので、記録として見せる
   */
  function 取り消す() {
    var 取り消す待ち = 待ち;
    if (!取り消す待ち || 送っている) return;
    待ちの様子 = '取り消し中';
    描く();
    送り直しつきで送る({ 操作: '打刻を取り消す', トークン: 鍵, 操作ID: 取り消す待ち.操作ID }, function (r) {
      return r.操作ID === 取り消す待ち.操作ID && typeof r.取り消した === 'boolean' &&
          (r.取り消した ? r.記録 === null : 打刻の形か(r.記録) && r.記録.種類 === 取り消す待ち.種類);
    }).then(function (結果) {
      if (待ち !== 取り消す待ち) return;
      if (!結果.届いた) {
        待ちの様子 = '届いていない';
        描く();
        知らせる('記録しないことを伝えられませんでした。電波のよい所で、もう一度押してください。');
        return;
      }
      if (!結果.応答.ok) { 待ちの様子 = '届いていない'; 断られた(結果.応答); return; }
      if (結果.応答.記録) { 届いた(結果.応答.記録); return; }
      待ちを消す();
      状態の文 = '記録しませんでした';
      描く();
    });
  }

  function 押した(種類) {
    if (待ち || !鍵) return;
    var 新しい待ち = { 操作ID: 新しい操作ID(), 種類: 種類, 押した: Date.now(), 鍵: 鍵 };
    // しまえないまま送ると、開き直した時に「届いたか分からない」打刻が消えて、押し直しで二重になり得る
    if (!しまう('待ち', 新しい待ち)) {
      知らせる('この端末に記録を残せないため、送りませんでした。画面を開き直してください。');
      return;
    }
    待ち = 新しい待ち;
    待ちの様子 = '';
    状態の文 = '';
    送り続ける();
  }

  function 送り続ける() {
    if (送っている || !待ち) return;
    if (待ち.鍵 !== 鍵) { 待ちの様子 = '別の登録'; 描く(); return; }
    送っている = true;
    待ちの様子 = '';
    描く();
    var 送る待ち = 待ち, 回 = 0;
    (function 一回() {
      setTimeout(function () {
        送る({ 操作: '打刻', トークン: 送る待ち.鍵, 種類: 送る待ち.種類, 操作ID: 送る待ち.操作ID }, function (r) {
          return 打刻の形か(r.記録) && r.記録.種類 === 送る待ち.種類;
        }).then(function (結果) {
          if (結果.届いた && 結果.応答.ok) { 届いた(結果.応答.記録); return; }
          // 混み合い・中の失敗は、時間をおけば通ることがある。ほかの断りは送り直しても同じ
          if (結果.届いた && ['混雑', '内部'].indexOf(結果.応答.コード) < 0) { 送っている = false; 断られた(結果.応答); return; }
          回++;
          if (回 < 送り直しの間隔.length) { 一回(); return; }
          送っている = false;
          描く();
        });
      }, 送り直しの間隔[回]);
    })();
  }

  function 届いた(r) {
    届いた回数++;
    待ち = null;
    待ちの様子 = '';
    しまう('待ち', null);
    送っている = false;
    記録 = [r].concat(記録.filter(function (x) { return x.記録ID !== r.記録ID; })).slice(0, 10);
    状態の文 = r.種類 + 'を記録しました（' + 時分(r.時刻) + '）';
    描く();
  }

  function 待ちを消す() {
    待ち = null;
    待ちの様子 = '';
    しまう('待ち', null);
    描く();
  }

  function 断られた(応答) {
    if (応答.コード === '未登録') {
      // 待ちは消さない（押した時のトークンに結び付いているので、登録し直しても送らずに知らせる）
      鍵 = null;
      しまう('トークン', null);
      登録の画面を出す(応答.理由, 登録できた);
      return;
    }
    // 回数の上限は、待てば送れるので「待ち」を残す。ほかの断りは裏で記録していないので消す
    if (応答.コード !== '回数' && 待ち) { 待ち = null; 待ちの様子 = ''; しまう('待ち', null); }
    描く();
    知らせる(応答.理由);
  }

  function 打刻の形か(r) {
    return !!r && typeof r.記録ID === 'string' && (r.種類 === '出勤' || r.種類 === '退勤') &&
        typeof r.時刻 === 'string' && /^\d{4}-\d\d-\d\d \d\d:\d\d:\d\d$/.test(r.時刻);
  }

  /** 待ちの帯の文とボタン。様子ごとに、押してよいボタンだけを出す */
  function 帯を描く() {
    var 帯 = 要素('待ちの知らせ'), 文 = 要素('待ちの文'), ボタン = 要素('待ちのボタン');
    帯.hidden = !(待ち && !送っている && 待ちの様子 !== '照会中' && 待ちの様子 !== '取り消し中');
    ボタン.textContent = '';
    if (帯.hidden) return;
    var いつ = 端末の時分(待ち.押した) + ' に押した「' + 待ち.種類 + '」';
    var 置く = function (名前, 控えめ, 押したら) {
      var b = 作る('button', { type: 'button', class: 'btn' + (控えめ ? ' ghost' : ''), text: 名前 });
      b.addEventListener('click', 押したら);
      ボタン.appendChild(b);
    };
    if (待ちの様子 === '別の登録') {
      文.textContent = '前の登録で ' + いつ + 'が残っています。この端末では送れないので、代表に伝えてください。';
      置く('消す', true, 待ちを消す);
    } else if (待ちの様子 === '届いていない') {
      文.textContent = いつ + 'は、届いていませんでした。';
      置く('いまの時刻で記録する', false, 送り続ける);
      置く('記録しない', true, 取り消す);
    } else {
      文.textContent = いつ + 'が、記録されたか確認できません。電波のよい所で「もう一度送る」を押してください（二重にはなりません）。';
      置く('もう一度送る', false, 送り続ける);
    }
  }

  function 描く() {
    var 今日 = 今日の日付();
    var 今日の記録 = 記録.filter(function (r) { return r.時刻.slice(0, 10) === 今日; });
    var 最後 = 今日の記録[0];
    var 最後の = function (種類) {
      return 今日の記録.filter(function (r) { return r.種類 === 種類; })[0];
    };

    ['出勤', '退勤'].forEach(function (種類) {
      var b = 要素(種類), 小 = 要素(種類 + 'の時刻');
      var 済 = 最後の(種類);
      if (待ち && 待ち.種類 === 種類) {
        小.textContent = 端末の時分(待ち.押した) + (送っている ? ' 送っています…' : 待ちの様子 === '照会中' ? ' 確かめています…' :
            待ちの様子 === '取り消し中' ? ' 取り消しています…' : ' 未確認');
      } else {
        小.textContent = 済 ? '記録 ' + 時分(済.時刻) : (種類 === '出勤' ? '押すと時刻が残る' : '—');
      }
      b.classList.toggle('pending', !!(待ち && 待ち.種類 === 種類));
      // 最後が出勤なら退勤だけ、それ以外は出勤だけを押せる。待ちがある間はどちらも押せない
      b.disabled = !!待ち || (種類 === '出勤' ? (最後 && 最後.種類 === '出勤') : !(最後 && 最後.種類 === '出勤'));
    });

    要素('状態').textContent = 状態の文;
    帯を描く();

    var 一覧 = 要素('記録');
    一覧.textContent = '';
    if (待ち) {
      var 押した日 = new Date(待ち.押した);
      一覧.appendChild(作る('li', { class: 'li pending' }, [
        作る('span', { class: 'd', text: (押した日.getMonth() + 1) + '/' + 押した日.getDate() }),
        作る('span', { text: 待ち.種類 + (送っている ? '（送信中）' : '（未確認）') }),
        作る('span', { class: 't', text: 端末の時分(待ち.押した) })
      ]));
    }
    記録.forEach(function (r) {
      一覧.appendChild(作る('li', { class: 'li' }, [
        作る('span', { class: 'd', text: 月日(r.時刻) }), 作る('span', { text: r.種類 }),
        作る('span', { class: 't', text: 時分(r.時刻) })
      ]));
    });
    if (!待ち && !記録.length) 一覧.appendChild(作る('li', { class: 'li empty', text: 'まだ記録はありません' }));
  }
})();
